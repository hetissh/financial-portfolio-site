  const toolbar = page.getByRole('group', { name: 'Paragraphs formatting', exact: true });
  await editor.fill('A formatted thought.');
  await editor.focus(); await expect(editor).toBeFocused();
  await editor.press(process.platform === 'darwin' ? 'Meta+a' : 'Control+a');
  await toolbar.getByRole('button', { name: 'Bold', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Italic', exact: true }).click();
