  await editor.press('ArrowRight'); await editor.press('End');
  // Native dialog focus and WebKit selection updates complete asynchronously.
  // Confirm a caret before Enter/type so we cannot replace the selected link text.
  await expect.poll(() => editor.evaluate(element => {
    const instance = (element as HTMLElement & { editor: { state: { selection: { empty: boolean } } } }).editor;
    const selection = window.getSelection();
    return instance.state.selection.empty && selection?.isCollapsed && element.contains(selection.anchorNode);
  })).toBe(true);
  await editor.press('Enter');
  if (await toolbar.getByRole('button', { name: 'Bold', exact: true }).getAttribute('aria-pressed') === 'true') await toolbar.getByRole('button', { name: 'Bold', exact: true }).click();
  if (await toolbar.getByRole('button', { name: 'Italic', exact: true }).getAttribute('aria-pressed') === 'true') await toolbar.getByRole('button', { name: 'Italic', exact: true }).click();
  await editor.pressSequentially('A useful point');
  await expect(editor.locator('strong')).toContainText('A formatted thought.');
  await toolbar.getByRole('button', { name: 'Bullets', exact: true }).click(); await expect(editor.locator('ul')).toHaveCount(1);
  await toolbar.getByRole('button', { name: '1, 2, 3', exact: true }).click(); await expect(editor.locator('ol')).toHaveCSS('list-style-type', 'decimal');
  await toolbar.getByRole('button', { name: 'a, b, c', exact: true }).click(); await expect(editor.locator('ol')).toHaveAttribute('type', 'a');
  await editor.press('End'); await editor.press('Enter'); await editor.press('Enter');
  await editor.pressSequentially('A deeper question');
  await toolbar.getByRole('button', { name: 'Subheading', exact: true }).click(); await expect(editor.locator('h3')).toContainText('A deeper question');
  await editor.press('End'); await editor.press('Enter'); await editor.pressSequentially('An image inside this paragraph: ');
  const png = await sharp({ create: { width: 200, height: 400, channels: 3, background: '#395f52' } }).png().toBuffer();
  await page.getByLabel('Image alternative text', { exact: true }).fill('A portrait chart example');
  await page.getByLabel('Image caption (optional)', { exact: true }).fill('Evidence illustration');
  await page.getByLabel('Import article image', { exact: true }).setInputFiles({ name: 'chart.png', mimeType: 'image/png', buffer: png });
  const image = editor.getByAltText('A portrait chart example'); await expect(image).toBeVisible();
  await expect(image).toHaveAttribute('height', '400');
  await image.click(); await page.getByRole('combobox', { name: 'Image width', exact: true }).selectOption('50');
  await page.getByRole('button', { name: 'Crop selected image', exact: true }).click();
  await page.getByRole('combobox', { name: 'Crop shape', exact: true }).selectOption('1');
  await page.getByRole('button', { name: 'Use this crop', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0); await expect(image).toHaveAttribute('height', '200'); await expect(editor.locator('.editor-article-image')).toHaveAttribute('style', /width: 50%/);
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue(`Formatted research ${info.project.name}`);
  await page.getByRole('button', { name: 'Create note', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/research\/note-\d+\/$/);
  const editUrl = page.url();
  await page.reload();
  await expect(editor.locator('strong')).toContainText('A formatted thought.'); await expect(editor.locator('ol')).toHaveAttribute('type', 'a');
  await expect(image).toHaveAttribute('alt', 'A portrait chart example');
  await editor.fill('An unsaved replacement');
  page.once('dialog', d => d.accept()); await page.getByRole('button', { name: 'Reset edits', exact: true }).click();
  await expect(image).toBeVisible(); await expect(editor.locator('h3')).toContainText('A deeper question');
