  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/admin/research/new/');
  await page.getByLabel('Title', { exact: true }).fill(`Formatted research ${info.project.name}`);
  await page.getByLabel('URL slug', { exact: true }).fill(`formatted-${info.project.name}`);
  await page.getByLabel('Summary', { exact: true }).fill('A formatting and image integration test.');
  await page.getByLabel('Category', { exact: true }).fill('Research');
